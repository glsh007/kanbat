/** Основа слова для грубого сравнения: «почтой» и «почта» → «почт». */
const stem = (w: string) => w.toLowerCase().replace(/ё/g, 'е').slice(0, 5);

/** Частые вопросы по похожести на текст обращения (сначала самые похожие). */
export function rankFaq(text: string): FaqTopic[] {
  const words = (
    text
      .toLowerCase()
      .replace(/ё/g, 'е')
      .match(/[a-zа-я-]{3,}/g) ?? []
  ).map(stem);
  const score = (t: FaqTopic) =>
    t.keywords.reduce((n, k) => {
      const kk = stem(k);
      return n + (words.some((w) => w.startsWith(kk) || kk.startsWith(w)) ? 1 : 0);
    }, 0);
  return FAQ.map((t, i) => ({ t, s: score(t), i }))
    .sort((a, b) => b.s - a.s || a.i - b.i)
    .map((x) => x.t);
}

export const faqById = (id: string) => FAQ.find((t) => t.id === id);
