export const PHRASE_WORDS = 6;

/** Новая случайная фраза: «сова ручей мост …». */
export function newPhrase(): string {
  return Array.from({ length: PHRASE_WORDS }, () => WORDS[randomInt(WORDS.length)]).join(' ');
}

/** Как человек ни ввёл фразу — регистр, «ё», запятые, лишние пробелы — сравниваем одинаково. */
export function normalizePhrase(raw: unknown): string {
  if (typeof raw !== 'string') return '';
  return raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^а-яa-z]+/)
    .filter(Boolean)
    .join(' ');
}
