/**
 * КОПИЯ apps/web/src/features/agent/honesty.ts — держать в синхроне (сверяет unit-honesty).
 * На сервере нужна для прогона проверочных вопросов (ТЗ v4.27): отчёт показывает то, что увидит человек.
 *
 * Помощник не умеет передавать обращение сам (ТЗ v4.23): это делает человек кнопкой
 * «Позвать специалиста». Модель всё равно иногда пишет «Обращение передано специалисту»
 * или спрашивает «Передать?» — и человек думает, что его уже ждут. Такие фразы заменяем
 * честной подсказкой про кнопку.
 */

export const BUTTON_HINT =
  'Сам передать обращение я не могу — нажмите «Позвать специалиста» внизу: он получит короткую сводку, пересказывать ничего не придётся.';

const TO_SPECIALIST =
  '(?:специалист|в поддержку|в техподдержку|мастер|техник|инженер|администратор|сотрудник[уа]м? поддержки|модератор)';

/** «Обращение передано специалисту», «Я передам вашу заявку администратору», «Отправил запрос мастеру». */
const CLAIM = new RegExp(
  '[^.!?\\n]*(?<![а-яё])(?:(?:могу|можем|помогу|помогу вам) передать|передал[аио]?|передан[оаы]?|передаю|передам|передадим|перевёл|перевел[аио]?|отправил[аио]?|отправлен[оаы]?|отправлю|направил[аио]?|направлен[оаы]?|направлю|созда[лн][аоы]? (?:заявк|обращени))[^.!?\\n]*' +
    TO_SPECIALIST +
    '[^.!?\\n]*[.!?…]*',
  'gi',
);

/** «Передать обращение специалисту?», «Хотите, я передам…?», «…или сразу передать обращение?» */
const ASK = new RegExp(
  '[^.!?\\n]*(?<![а-яё])(?:передать|передам|передал бы|отправить|направить)(?![а-яё])[^.!?\\n]*\\?',
  'gi',
);

/** Обещания визита или звонка после «передачи»: «Он скоро свяжется с вами», «приедет на место». */
const PROMISE =
  /[^.!?\n]*(?<![а-яё])(?:свяжется|перезвонит|приедет|подойдёт|подойдет|напишет вам|скоро ответит)(?![а-яё])[^.!?\n]*[.!?…]*/gi;

/** Есть ли в ответе выдуманная передача или вопрос «передать?». */
export function claimsHandoff(text: string): boolean {
  CLAIM.lastIndex = 0;
  ASK.lastIndex = 0;
  return (
    CLAIM.test(text) || (ASK.test(text) && /специалист|поддержк|мастер|администратор/i.test(text))
  );
}

/**
 * Убрать выдуманную передачу (и обещания, которые из неё следуют) и один раз добавить подсказку
 * про кнопку. Текст без таких фраз не меняется.
 */
export function honestHandoff(text: string): string {
  if (!claimsHandoff(text)) return text;
  let out = text.replace(CLAIM, ' ');
  // вопрос «передать?» — только если он про специалиста (а не «передать показания счётчика?»)
  out = out.replace(ASK, (m) =>
    /специалист|поддержк|мастер|администратор|обращени|заявк/i.test(m) ? ' ' : m,
  );
  out = out.replace(PROMISE, ' ');
  out = out
    .split('\n')
    .map((l) => l.replace(/[ \t]{2,}/g, ' ').trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return out ? `${out}\n\n${BUTTON_HINT}` : BUTTON_HINT;
}
